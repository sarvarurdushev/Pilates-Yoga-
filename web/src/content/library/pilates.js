/**
 * The Pilates repertoire, as records. See ./compose.js for how a record becomes an entry.
 *
 * Poses are in degrees, in the rig's own coordinates. `lumbar_flex` / `thoracic_flex` /
 * `cervical_flex` are regional commands distributed across the individual vertebral joints
 * by their published segmental ranges, and `*_wave` sweeps a flexion front along a region —
 * which is what finally lets a roll-up peel one segment at a time instead of hinging as a
 * block.
 *
 * Muscle roles carry `emg` only where a study measured that muscle in that movement or in
 * the same joint action under the same load. Everything else is `inferred`, which for most
 * mat work is the honest answer.
 */

