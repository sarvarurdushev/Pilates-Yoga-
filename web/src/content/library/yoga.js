/**
 * The yoga repertoire, as records. See ./compose.js for how a record becomes an entry.
 *
 * Same shape as the Pilates library and the same rules. Poses are in degrees in the rig's
 * own coordinates; `lumbar_flex` / `thoracic_flex` / `cervical_flex` are regional commands
 * distributed across the vertebral joints by each level's published range on that axis, and
 * positive is flexion.
 *
 * **Sanskrit is transliterated IAST without diacritics**, which is what a studio actually
 * writes on a whiteboard. Where a pose has more than one common name the one in use in
 * modern postural yoga is used, and the tradition it comes from is not asserted: the
 * historical lineage of most of these shapes is contested and this app has no business
 * taking a side in it.
 *
 * **Every muscle role here is `inferred` unless a study measured it.** Surface EMG of yoga
 * asana exists for a handful of shapes — chaturanga, plank, warrior variants, the standard
 * hip and hamstring positions — and for the underlying joint actions generally. It does not
 * exist for most of this list, and the note on each entry says which case it is.
 */

